leadForm?.addEventListener("submit", async (event) => {
  event.preventDefault();

  if (!leadForm.reportValidity()) return;

  const payload = buildLeadPayload(leadForm);
  const submitButton = leadForm.querySelector('[type="submit"]');

  submitButton?.setAttribute("disabled", "true");
  setLeadStatus("lead.statusSending");

  if (!leadConfig.endpoint) {
    window.location.href = createLeadEmailLink(payload);
    setLeadStatus("lead.statusMailFallback", "success");
    submitButton?.removeAttribute("disabled");
    return;
  }

  try {
    const response = await fetch(leadConfig.endpoint, {
      method: "POST",
      headers: {
        Accept: "application/json",
        "Content-Type": "application/json",
      },
      body: JSON.stringify(payload),
    });

    if (!response.ok) {
      throw new Error(`Lead endpoint returned ${response.status}`);
    }

    leadForm.reset();
    setLeadStatus("lead.statusSuccess", "success");
  } catch (error) {
    setLeadStatus("lead.statusError", "error");
  } finally {
    submitButton?.removeAttribute("disabled");
  }
});

const getViewFromHash = () => {
  const hashView = window.location.hash.replace("#", "");
  const routedView = routeAliases[hashView] || hashView;
  return viewNames.has(routedView) ? routedView : "home";
};

const setActiveView = (view, updateHash = true) => {
  const routedView = routeAliases[view] || view;
  const activeView = viewNames.has(routedView) ? routedView : "home";

  viewPanels.forEach((panel) => {
    const isActive = panel.dataset.view === activeView;
    panel.classList.toggle("is-active", isActive);
    panel.toggleAttribute("hidden", !isActive);
  });

  routeLinks.forEach((link) => {
    link.classList.toggle("is-active", link.dataset.route === activeView);
  });

  if (updateHash && window.location.hash !== `#${activeView}`) {
    window.history.pushState(null, "", `#${activeView}`);
  }

  window.scrollTo({ top: 0, behavior: "smooth" });
  closeMenu();
};

routeLinks.forEach((link) => {
  link.addEventListener("click", (event) => {
    const route = link.dataset.route;
    if (!route) return;
    event.preventDefault();
    setActiveView(route);
  });
});

window.addEventListener("hashchange", () => {
  setActiveView(getViewFromHash(), false);
});

setActiveView(getViewFromHash(), false);

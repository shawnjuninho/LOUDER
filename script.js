const languageCodes = {
  en: "en",
  ms: "ms",
  th: "th",
  zh: "zh-CN",
};

const languageMeta = {
  en: { label: "English", flagClass: "flag-us" },
  ms: { label: "Bahasa Melayu", flagClass: "flag-my" },
  th: { label: "ไทย", flagClass: "flag-th" },
  zh: { label: "中文", flagClass: "flag-cn" },
};

const header = document.querySelector("[data-header]");
const menuToggle = document.querySelector(".menu-toggle");
const mobileNav = document.querySelector("[data-mobile-nav]");
const languageTrigger = document.querySelector("[data-language-trigger]");
const languageOptions = document.querySelector("[data-language-options]");
const languageOptionButtons = document.querySelectorAll("[data-lang-option]");
const currentLanguageLabel = document.querySelector("[data-current-language]");
const currentLanguageFlag = languageTrigger?.querySelector(".flag");

const getPreferredLanguage = () => {
  const savedLanguage = localStorage.getItem("louder-language");
  return savedLanguage && translations[savedLanguage] ? savedLanguage : "en";
};

const setLanguage = (language) => {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = languageCodes[language] || "en";
  document.documentElement.dataset.language = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (key && dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  if (currentLanguageLabel && languageMeta[language]) {
    currentLanguageLabel.textContent = languageMeta[language].label;
  }

  if (currentLanguageFlag && languageMeta[language]) {
    currentLanguageFlag.className = `flag ${languageMeta[language].flagClass}`;
  }

  languageOptionButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.langOption === language);
  });

  const isMenuOpen = document.body.classList.contains("menu-open");
  menuToggle?.setAttribute("aria-label", dictionary[isMenuOpen ? "menu.close" : "menu.open"]);
  localStorage.setItem("louder-language", language);
};

const closeMenu = () => {
  document.body.classList.remove("menu-open");
  mobileNav?.classList.remove("is-open");
  menuToggle?.setAttribute("aria-expanded", "false");
  const language = document.documentElement.dataset.language || "en";
  menuToggle?.setAttribute("aria-label", translations[language]["menu.open"]);
};

const closeLanguageMenu = () => {
  if (!languageOptions || !languageTrigger) return;
  languageOptions.hidden = true;
  languageTrigger.setAttribute("aria-expanded", "false");
};

const updateHeader = () => {
  header?.classList.toggle("is-scrolled", window.scrollY > 16);
};

setLanguage(getPreferredLanguage());
updateHeader();
window.addEventListener("scroll", updateHeader, { passive: true });

languageTrigger?.addEventListener("click", () => {
  if (!languageOptions) return;
  const shouldOpen = languageOptions.hidden;
  languageOptions.hidden = !shouldOpen;
  languageTrigger.setAttribute("aria-expanded", String(shouldOpen));
});

languageOptionButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.langOption || "en");
    closeLanguageMenu();
  });
});

menuToggle?.addEventListener("click", () => {
  const isOpen = document.body.classList.toggle("menu-open");
  const language = document.documentElement.dataset.language || "en";
  mobileNav?.classList.toggle("is-open", isOpen);
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  menuToggle.setAttribute("aria-label", translations[language][isOpen ? "menu.close" : "menu.open"]);
});

mobileNav?.addEventListener("click", (event) => {
  if (event.target instanceof HTMLAnchorElement) {
    closeMenu();
  }
});

window.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeMenu();
    closeLanguageMenu();
  }
});

document.addEventListener("click", (event) => {
  if (event.target instanceof Element && !event.target.closest("[data-language-menu]")) {
    closeLanguageMenu();
  }
});

const canvas = document.querySelector("#ambientCanvas");
const context = canvas?.getContext("2d");
const pointer = { x: 0.64, y: 0.42 };
let width = 0;
let height = 0;
let nodes = [];

const resizeCanvas = () => {
  if (!canvas || !context) return;
  const ratio = Math.min(window.devicePixelRatio || 1, 2);
  width = window.innerWidth;
  height = window.innerHeight;
  canvas.width = Math.floor(width * ratio);
  canvas.height = Math.floor(height * ratio);
  canvas.style.width = `${width}px`;
  canvas.style.height = `${height}px`;
  context.setTransform(ratio, 0, 0, ratio, 0, 0);

  const nodeCount = width < 700 ? 30 : 54;
  nodes = Array.from({ length: nodeCount }, (_, index) => ({
    x: (index * 197) % Math.max(width, 1),
    y: (index * 113) % Math.max(height, 1),
    vx: ((index % 7) - 3) * 0.04,
    vy: ((index % 5) - 2) * 0.035,
  }));
};

const drawAmbient = () => {
  if (!context) return;
  context.clearRect(0, 0, width, height);
  context.fillStyle = "rgba(247, 249, 247, 0.42)";
  context.fillRect(0, 0, width, height);

  const focusX = pointer.x * width;
  const focusY = pointer.y * height;
  const glow = context.createRadialGradient(focusX, focusY, 0, focusX, focusY, Math.max(width, height) * 0.72);
  glow.addColorStop(0, "rgba(110, 231, 242, 0.16)");
  glow.addColorStop(0.35, "rgba(255, 212, 61, 0.08)");
  glow.addColorStop(1, "rgba(247, 249, 247, 0)");
  context.fillStyle = glow;
  context.fillRect(0, 0, width, height);

  nodes.forEach((node, index) => {
    node.x += node.vx;
    node.y += node.vy;

    if (node.x < -40) node.x = width + 40;
    if (node.x > width + 40) node.x = -40;
    if (node.y < -40) node.y = height + 40;
    if (node.y > height + 40) node.y = -40;

    for (let nextIndex = index + 1; nextIndex < nodes.length; nextIndex += 1) {
      const next = nodes[nextIndex];
      const distance = Math.hypot(node.x - next.x, node.y - next.y);

      if (distance < 170) {
        context.strokeStyle = `rgba(6, 20, 23, ${0.09 - distance / 2400})`;
        context.lineWidth = 1;
        context.beginPath();
        context.moveTo(node.x, node.y);
        context.lineTo(next.x, next.y);
        context.stroke();
      }
    }

    context.fillStyle = index % 8 === 0 ? "rgba(243, 176, 0, 0.5)" : "rgba(6, 20, 23, 0.24)";
    context.beginPath();
    context.arc(node.x, node.y, index % 8 === 0 ? 2.4 : 1.6, 0, Math.PI * 2);
    context.fill();
  });

  window.requestAnimationFrame(drawAmbient);
};

window.addEventListener(
  "pointermove",
  (event) => {
    pointer.x = event.clientX / Math.max(window.innerWidth, 1);
    pointer.y = event.clientY / Math.max(window.innerHeight, 1);
  },
  { passive: true },
);

window.addEventListener("resize", resizeCanvas);
resizeCanvas();
drawAmbient();

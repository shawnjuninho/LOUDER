const setLanguage = (language) => {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = languageCodes[language] || "en";
  document.documentElement.dataset.language = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (key && dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (key && dictionary[key]) {
      element.setAttribute("placeholder", dictionary[key]);
    }
  });

  if (currentLanguageLabel && languageMeta[language]) {
    currentLanguageLabel.textContent = languageMeta[language].label;
  }

  if (currentLanguageFlag && languageMeta[language]) {
    currentLanguageFlag.className = `flag ${languageMeta[language].flagClass}`;
  }

  languageOptionButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.langOption === language);
  });

  const isMenuOpen = document.body.classList.contains("menu-open");
  menuToggle?.setAttribute("aria-label", dictionary[isMenuOpen ? "menu.close" : "menu.open"]);
  localStorage.setItem("louder-language", language);
};

